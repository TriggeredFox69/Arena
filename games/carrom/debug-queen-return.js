import { TURN, SIDE, createInitialState, baselineFor, BOARD_SIZE, MARGIN, STRIKER_R, COIN_R } from './state.js';
import { Simulation } from './core/simulation.js';
import { isValidStrikerPlacement, findClearStrikerX } from './core/collision.js';
import { resolveTurn, applyTurnPatch } from './rules/rules-engine.js';

const s = createInitialState('ai', 'medium');
s.turn = TURN.P1; s.p1Side = SIDE.WHITE; s.p2Side = SIDE.BLACK;
const ownCoin = s.coins.find(c => c.side === s.p1Side);
for (const c of s.coins) if (c.id !== ownCoin.id && c.color !== 'red') c.active = false;
const queen = s.coins.find(c => c.color === 'red');
const pocket = { x: BOARD_SIZE - MARGIN - 10, y: MARGIN + 10 };
const baselineY = baselineFor(TURN.P1);
const uy = pocket.y - queen.y;
const ux = pocket.x - queen.x;
const t = (baselineY - queen.y) / uy;
let sx = queen.x + t * ux;
sx = Math.max(MARGIN + STRIKER_R + 2, Math.min(BOARD_SIZE - MARGIN - STRIKER_R - 2, sx));
if (!isValidStrikerPlacement(sx, baselineY, s.coins)) sx = findClearStrikerX(baselineY, s.coins, sx);
console.log('queen', queen.x, queen.y, 'sx', sx, 'baselineY', baselineY);
const dx = queen.x - pocket.x;
const dy = queen.y - pocket.y;
const d = Math.hypot(dx, dy);
const gx = queen.x + (dx / d) * (COIN_R + STRIKER_R + 0.5);
const gy = queen.y + (dy / d) * (COIN_R + STRIKER_R + 0.5);
const dirX = gx - sx;
const dirY = gy - baselineY;
const dirLen = Math.hypot(dirX, dirY);
const sim = new Simulation(s);
sim.setStriker(sx, baselineY);
sim.shoot((dirX / dirLen) * 620, (dirY / dirLen) * 620);
sim.runUntilSettled(5000);
const pockets = sim.events.filter(e => e.type === 'pocket');
console.log('pockets', pockets);
const patch = resolveTurn(s, pockets);
console.log('patch', patch);
applyTurnPatch(s, patch);
console.log('turn', s.turn, 'scores', s.scores, 'queen active', s.coins.find(c=>c.color==='red').active, 'phase', s.phase, 'winner', s.winner);
